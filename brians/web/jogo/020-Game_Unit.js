  // ● 敏捷性平均値の計算
  //--------------------------------------------------------------------------
  average_agi() {
    let result, n, member;
    result = 0;
    n = 0;
    for (member of this.members) {
      result = rb.add(result, member.agi);
      n += 1;
    }
    if ((n > 0)) {
      result = rb.div(result, n);
    }
    if ((result === 0)) {
      result = 1;
    }
    return result;
  }
