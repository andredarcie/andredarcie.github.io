  get interpreter() { return this._interpreter; } // バトルイベント用インタプリタ
  get event_flags() { return this._event_flags; } // バトルイベント実行済みフラグ
  get turn_count() { return this._turn_count; } // ターン数
  get name_counts() { return this._name_counts; } // 敵キャラ名の出現数記録ハッシュ
  get can_escape() { return this._can_escape; }
  set can_escape(v) { this._can_escape = v; } // 逃走可能フラグ
  get can_lose() { return this._can_lose; }
  set can_lose(v) { this._can_lose = v; } // 敗北可能フラグ
  get preemptive() { return this._preemptive; }
  set preemptive(v) { this._preemptive = v; } // 先制攻撃フラグ
  get surprise() { return this._surprise; }
  set surprise(v) { this._surprise = v; } // 不意打ちフラグ
  get turn_ending() { return this._turn_ending; }
  set turn_ending(v) { this._turn_ending = v; } // ターン終了処理中フラグ
  get forcing_battler() { return this._forcing_battler; }
  set forcing_battler(v) { this._forcing_battler = v; } // 戦闘行動の強制対象
  //--------------------------------------------------------------------------
  // ● オブジェクト初期化
  //--------------------------------------------------------------------------
  async initialize() {
    super.initialize();
    this._screen = Game_Screen.new();
    this._interpreter = (await Game_Interpreter.new());
    this._event_flags = rb.hash([]);
    this._enemies = []; // トループメンバー (敵キャラオブジェクトの配列)
    this.clear();
  }
  //--------------------------------------------------------------------------
  // ● メンバーの取得
  //--------------------------------------------------------------------------
  get members() {
    return this._enemies;
  }
  //--------------------------------------------------------------------------
  // ● クリア
  //--------------------------------------------------------------------------
  clear() {
    rb.clear(this._screen);
    rb.clear(this._interpreter);
    rb.clear(this._event_flags);
    this._enemies = [];
    this._turn_count = 0;
    this._names_count = rb.hash([]);
    this._can_escape = false;
    this._can_lose = false;
    this._preemptive = false;
    this._surprise = false;
    this._turn_ending = false;
    return this._forcing_battler = null;
  }
  setup() { return rb.foraDoEscopo("Game_Troop#setup", "só prepara inimigos para uma batalha, e o jogo não tem batalha (o update_encounter sai antes, porque nenhum mapa tem encontros)"); }
  //--------------------------------------------------------------------------
  // ● 敵グループオブジェクト取得
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● セットアップ
  //     troop_id : 敵グループ ID
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 同名の敵キャラに ABC などの文字を付加
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● フレーム更新
  //--------------------------------------------------------------------------
  update() {
    return this._screen.update();
  }
