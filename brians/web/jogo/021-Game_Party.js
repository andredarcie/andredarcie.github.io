import * as rb from 'rb'; // import map: web/src/rb/rb.js

//==============================================================================
// ■ Game_Party
//------------------------------------------------------------------------------
// 　パーティを扱うクラスです。ゴールドやアイテムなどの情報が含まれます。このク
// ラスのインスタンスは $game_party で参照されます。
//==============================================================================
globalThis.Game_Party = rb.classe("Game_Party", class Game_Party extends Game_Unit {
});
//--------------------------------------------------------------------------
// ● 定数
//--------------------------------------------------------------------------
Game_Party.MAX_MEMBERS = 4; // 最大パーティ人数
//--------------------------------------------------------------------------
// ● 公開インスタンス変数
//--------------------------------------------------------------------------
rb.reabrir(Game_Party, class extends rb.superDe(Game_Party) {
  get gold() { return this._gold; } // ゴールド
  get steps() { return this._steps; } // 歩数
  get last_item_id() { return this._last_item_id; }
  set last_item_id(v) { this._last_item_id = v; } // カーソル記憶用 : アイテム
  get last_actor_index() { return this._last_actor_index; }
  set last_actor_index(v) { this._last_actor_index = v; } // カーソル記憶用 : アクター
  get last_target_index() { return this._last_target_index; }
  set last_target_index(v) { this._last_target_index = v; } // カーソル記憶用 : ターゲット
  //--------------------------------------------------------------------------
  // ● オブジェクト初期化
  //--------------------------------------------------------------------------
  initialize() {
    super.initialize();
    this._gold = 0;
    this._steps = 0;
    this._last_item_id = 0;
    this._last_actor_index = 0;
    this._last_target_index = 0;
    this._actors = []; // パーティメンバー (アクター ID)
    this._items = rb.hash([]); // 所持品ハッシュ (アイテム ID)
    this._weapons = rb.hash([]); // 所持品ハッシュ (武器 ID)
    this._armors = rb.hash([]); // 所持品ハッシュ (防具 ID)
  }
  //--------------------------------------------------------------------------
  // ● メンバーの取得
  //--------------------------------------------------------------------------
  get members() {
    let result, i;
    result = [];
    for (i of this._actors) {
      rb.push(result, rb.idx($game_actors, i));
    }
    return result;
  }
  //--------------------------------------------------------------------------
  // ● アイテムオブジェクトの配列取得 (武器と防具を含む)
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 初期パーティのセットアップ
  //--------------------------------------------------------------------------
  setup_starting_members() {
    let i;
    this._actors = [];
    for (i of $data_system.party_members) {
      rb.push(this._actors, i);
    }
  }
  //--------------------------------------------------------------------------
  // ● パーティ名の取得
  //    一人ならそのアクターの名前、複数なら "○○たち" を返す。
  //--------------------------------------------------------------------------
  get name() {
    if ((rb.size(this._actors) === 0)) {
      return "";
    } else if ((rb.size(this._actors) === 1)) {
      return rb.idx(this.members, 0).name;
    } else {
      return rb.sprintf(Vocab.PartyName, rb.idx(this.members, 0).name);
    }
  }
  //--------------------------------------------------------------------------
  // ● 戦闘テスト用パーティのセットアップ
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 最大レベルの取得
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● アクターを加える
  //     actor_id : アクター ID
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● アクターを外す
  //     actor_id : アクター ID
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● ゴールドの増加 (減少)
  //     n : 金額
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● ゴールドの減少
  //     n : 金額
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 歩数増加
  //--------------------------------------------------------------------------
  increase_steps() {
    return this._steps += 1;
  }
  //--------------------------------------------------------------------------
  // ● アイテムの所持数取得
  //     item : アイテム
  //--------------------------------------------------------------------------
  item_number(item) {
    let number;
    const caso1 = item;
    if (rb.caseEq(RPG.Item, caso1)) {
      number = rb.idx(this._items, rb.id(item));
    } else if (rb.caseEq(RPG.Weapon, caso1)) {
      number = rb.idx(this._weapons, rb.id(item));
    } else if (rb.caseEq(RPG.Armor, caso1)) {
      number = rb.idx(this._armors, rb.id(item));
    }
    return ((number == null) ? 0 : number);
  }
  //--------------------------------------------------------------------------
  // ● アイテムの所持判定
  //     item          : アイテム
  //     include_equip : 装備品も含める
  //--------------------------------------------------------------------------
  has_item_p(item, include_equip = false) {
    let actor;
    if ((this.item_number(item) > 0)) {
      return true;
    }
    if (rb.v(include_equip)) {
      for (actor of this.members) {
        if (rb.include_p(actor.equips(), item)) {
          return true;
        }
      }
    }
    return false;
  }
  //--------------------------------------------------------------------------
  // ● アイテムの増加 (減少)
  //     item          : アイテム
  //     n             : 個数
  //     include_equip : 装備品も含める
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● アイテムの減少
  //     item          : アイテム
  //     n             : 個数
  //     include_equip : 装備品も含める
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● アイテムの消耗
  //     item : アイテム
  //    指定されたオブジェクトが消耗アイテムであれば、所持数を 1 減らす。
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● アイテムの使用可能判定
  //     item : アイテム
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● コマンド入力可能判定
  //    自動戦闘は入力可能として扱う。
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 全滅判定
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● プレイヤーが 1 歩動いたときの処理
  //--------------------------------------------------------------------------
  on_player_walk() {
    let actor;
    for (actor of this.members) {
      if (actor.slip_damage_p()) {
        if ((actor.hp > 1)) { // 毒ダメージ
          actor.hp -= 1;
        }
        $game_map.screen.start_flash(Color.new(255, 0, 0, 64), 4);
      }
      if (actor.auto_hp_recover && (actor.hp > 0)) {
        actor.hp += 1; // HP 自動回復
      }
    }
  }
  // fora do escopo (nada do jogo chama): items, setup_battle_test_members, max_level, add_actor, remove_actor, gain_gold, lose_gold, gain_item, lose_item, consume_item, item_can_use?, inputable?, all_dead?, do_auto_recovery, remove_states_battle
});
