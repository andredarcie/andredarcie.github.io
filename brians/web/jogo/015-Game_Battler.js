  // ● 回避可能判定
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 沈黙状態判定
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 暴走状態判定
  //--------------------------------------------------------------------------
