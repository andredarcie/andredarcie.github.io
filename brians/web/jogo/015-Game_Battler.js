  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 属性修正値の取得
  //     element_id : 属性 ID
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● ステートの付加成功率の取得
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● ステート無効化判定
  //     state_id : ステート ID
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 通常攻撃の属性取得
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 通常攻撃のステート変化 (+) 取得
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 通常攻撃のステート変化 (-) 取得
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● ステートの検査
  //     state_id : ステート ID
  //    該当するステートが付加されていれば true を返す。
  //--------------------------------------------------------------------------
  state_p(state_id) {
    return rb.include_p(this._states, state_id);
  }
  //--------------------------------------------------------------------------
  // ● ステートがフルかどうかの判定
  //     state_id : ステート ID
  //    持続ターン数が自然解除の最低ターン数と同じなら true を返す。
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 無視するべきステートかどうかの判定
  //     state_id : ステート ID
  //    次の条件を満たすときに true を返す。
  //    ＊付加しようとする新しいステートＡが、現在付加されているステートＢの
  //      [解除するステート] のリストに含まれている。
  //    ＊そのステートＢが新しいステートＡの [解除するステート] のリストには
  //      含まれていない。
  //    この条件は、戦闘不能のときに毒を付加しようとした場合などに該当する。
  //    攻撃力下降のときに攻撃力上昇を付加するような場合には該当しない。
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 相殺するべきステートかどうかの判定
  //     state_id : ステート ID
  //    次の条件を満たすときに true を返す。
  //    ＊新しいステートのオプション [逆効果と相殺] が有効である。
  //    ＊付加しようとする新しいステートの [解除するステート] のリストに、
  //      現在付加されているステートの少なくともひとつが含まれている。
  //    攻撃力下降のときに攻撃力上昇を付加する場合などに該当する。
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● ステートの並び替え
  //    配列 @states の内容を表示優先度の大きい順に並び替える。
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● ステートの付加
  //     state_id : ステート ID
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● ステートの解除
  //     state_id : ステート ID
  //--------------------------------------------------------------------------
  remove_state(state_id) {
    if (!(this.state_p(state_id))) {
      return; // このステートが付加されていない？
    }
    if ((state_id === 1) && (this._hp === 0)) { // 戦闘不能 (ステート 1 番) なら
      this._hp = 1; // HP を 1 に変更する
    }
    rb.delete(this._states, state_id); // ID を @states 配列から削除
    return rb.delete(this._state_turns, state_id); // ターン数記憶用ハッシュから削除
  }
  //--------------------------------------------------------------------------
  // ● 制約の取得
  //    現在付加されているステートから最大の restriction を取得する。
  //--------------------------------------------------------------------------
  get restriction() {
    let restriction_max, state;
    restriction_max = 0;
    for (state of this.states()) {
      if ((state.restriction >= restriction_max)) {
        restriction_max = state.restriction;
      }
    }
    return restriction_max;
  }
  //--------------------------------------------------------------------------
  // ● ステート [スリップダメージ] 判定
  //--------------------------------------------------------------------------
  slip_damage_p() {
    let state;
    for (state of this.states()) {
      if (state.slip_damage) {
        return true;
      }
    }
    return false;
  }
