import * as rb from 'rb'; // import map: web/src/rb/rb.js

//==============================================================================
// ■ Game_Actor
//------------------------------------------------------------------------------
// 　アクターを扱うクラスです。このクラスは Game_Actors クラス ($game_actors)
// の内部で使用され、Game_Party クラス ($game_party) からも参照されます。
//==============================================================================
//--------------------------------------------------------------------------
// ● 公開インスタンス変数
//--------------------------------------------------------------------------
globalThis.Game_Actor = rb.classe("Game_Actor", class Game_Actor extends Game_Battler {
  get name() { return this._name; } // 名前
  get character_name() { return this._character_name; } // 歩行グラフィック ファイル名
  get character_index() { return this._character_index; } // 歩行グラフィック インデックス
  get face_name() { return this._face_name; } // 顔グラフィック ファイル名
  get face_index() { return this._face_index; } // 顔グラフィック インデックス
  get class_id() { return this._class_id; } // 職業 ID
  get weapon_id() { return this._weapon_id; } // 武器 ID
  get armor1_id() { return this._armor1_id; } // 盾 ID
  get armor2_id() { return this._armor2_id; } // 頭防具 ID
  get armor3_id() { return this._armor3_id; } // 体防具 ID
  get armor4_id() { return this._armor4_id; } // 装飾品 ID
  get level() { return this._level; } // レベル
  get exp() { return this._exp; } // 経験値
  get last_skill_id() { return this._last_skill_id; }
  set last_skill_id(v) { this._last_skill_id = v; } // カーソル記憶用 : スキル
  //--------------------------------------------------------------------------
  // ● オブジェクト初期化
  //     actor_id : アクター ID
  //--------------------------------------------------------------------------
  initialize(actor_id) {
    super.initialize();
    this.setup(actor_id);
    this._last_skill_id = 0;
  }
  //--------------------------------------------------------------------------
  // ● セットアップ
  //     actor_id : アクター ID
  //--------------------------------------------------------------------------
  setup(actor_id) {
    let actor, i;
    actor = rb.idx($data_actors, actor_id);
    this._actor_id = actor_id;
    this._name = actor.name;
    this._character_name = actor.character_name;
    this._character_index = actor.character_index;
    this._face_name = actor.face_name;
    this._face_index = actor.face_index;
    this._class_id = actor.class_id;
    this._weapon_id = actor.weapon_id;
    this._armor1_id = actor.armor1_id;
    this._armor2_id = actor.armor2_id;
    this._armor3_id = actor.armor3_id;
    this._armor4_id = actor.armor4_id;
    this._level = actor.initial_level;
    this._exp_list = rb.novo(rb.Array, 101);
    this.make_exp_list();
    this._exp = rb.idx(this._exp_list, this._level);
    this._skills = [];
    for (i of this.class().learnings) {
      if ((i.level <= this._level)) {
        this.learn_skill(i.skill_id);
      }
    }
    this.clear_extra_values();
    return this.recover_all();
  }
  //--------------------------------------------------------------------------
  // ● アクターか否かの判定
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● アクター ID 取得
  //--------------------------------------------------------------------------
  get id() {
    return this._actor_id;
  }
  //--------------------------------------------------------------------------
  // ● インデックス取得
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● アクターオブジェクト取得
  //--------------------------------------------------------------------------
  actor() {
    return rb.idx($data_actors, this._actor_id);
  }
  //--------------------------------------------------------------------------
  // ● 職業オブジェクト取得
  //--------------------------------------------------------------------------
  class() {
    return rb.idx($data_classes, this._class_id);
  }
  //--------------------------------------------------------------------------
  // ● スキルオブジェクトの配列取得
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 武器オブジェクトの配列取得
  //--------------------------------------------------------------------------
  weapons() {
    let result;
    result = [];
    rb.push(result, rb.idx($data_weapons, this._weapon_id));
    if (this.two_swords_style) {
      rb.push(result, rb.idx($data_weapons, this._armor1_id));
    }
    return result;
  }
  //--------------------------------------------------------------------------
  // ● 防具オブジェクトの配列取得
  //--------------------------------------------------------------------------
  armors() {
    let result;
    result = [];
    if (!(this.two_swords_style)) {
      rb.push(result, rb.idx($data_armors, this._armor1_id));
    }
    rb.push(result, rb.idx($data_armors, this._armor2_id));
    rb.push(result, rb.idx($data_armors, this._armor3_id));
    rb.push(result, rb.idx($data_armors, this._armor4_id));
    return result;
  }
  //--------------------------------------------------------------------------
  // ● 装備品オブジェクトの配列取得
  //--------------------------------------------------------------------------
  equips() {
    return rb.add(this.weapons(), this.armors());
  }
  //--------------------------------------------------------------------------
  // ● 経験値計算
  //--------------------------------------------------------------------------
  make_exp_list() {
    let m, n, i;
    rb.idxSet(this._exp_list, 1, rb.idxSet(this._exp_list, 100, 0));
    m = this.actor().exp_basis;
    n = (0.75 + (this.actor().exp_inflation / 200.0));
    for (i of rb.range(2, 99, false)) {
      rb.idxSet(this._exp_list, i, rb.add(rb.idx(this._exp_list, (i - 1)), rb.Integer(m)));
      m = rb.mul(m, (1 + n));
      n *= 0.9;
    }
  }
  //--------------------------------------------------------------------------
  // ● 属性修正値の取得
  //     element_id : 属性 ID
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● ステートの付加成功率の取得
  //     state_id : ステート ID
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● ステート無効化判定
  //     state_id : ステート ID
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 通常攻撃の属性取得
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 通常攻撃の追加効果 (ステート変化) 取得
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● MaxHP の制限値取得
  //--------------------------------------------------------------------------
  maxhp_limit() {
    return 9999;
  }
  //--------------------------------------------------------------------------
  // ● 基本 MaxHP の取得
  //--------------------------------------------------------------------------
  base_maxhp() {
    return rb.idx(this.actor().parameters, 0, this._level);
  }
  //--------------------------------------------------------------------------
  // ● 基本 MaxMP の取得
  //--------------------------------------------------------------------------
  base_maxmp() {
    return rb.idx(this.actor().parameters, 1, this._level);
  }
  //--------------------------------------------------------------------------
  // ● 基本攻撃力の取得
  //--------------------------------------------------------------------------
  base_atk() {
    let n, item;
    n = rb.idx(this.actor().parameters, 2, this._level);
    for (item of rb.compact(this.equips())) {
      n = rb.add(n, item.atk);
    }
    return n;
  }
  //--------------------------------------------------------------------------
  // ● 基本防御力の取得
  //--------------------------------------------------------------------------
  base_def() {
    let n, item;
    n = rb.idx(this.actor().parameters, 3, this._level);
    for (item of rb.compact(this.equips())) {
      n = rb.add(n, item.def);
    }
    return n;
  }
  //--------------------------------------------------------------------------
  // ● 基本精神力の取得
  //--------------------------------------------------------------------------
  base_spi() {
    let n, item;
    n = rb.idx(this.actor().parameters, 4, this._level);
    for (item of rb.compact(this.equips())) {
      n = rb.add(n, item.spi);
    }
    return n;
  }
  //--------------------------------------------------------------------------
  // ● 基本敏捷性の取得
  //--------------------------------------------------------------------------
  base_agi() {
    let n, item;
    n = rb.idx(this.actor().parameters, 5, this._level);
    for (item of rb.compact(this.equips())) {
      n = rb.add(n, item.agi);
    }
    return n;
  }
  //--------------------------------------------------------------------------
  // ● 命中率の取得
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 回避率の取得
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● クリティカル率の取得
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 狙われやすさの取得
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● オプション [二刀流] の取得
  //--------------------------------------------------------------------------
  get two_swords_style() {
    return this.actor().two_swords_style;
  }
  //--------------------------------------------------------------------------
  // ● オプション [装備固定] の取得
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● オプション [自動戦闘] の取得
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● オプション [強力防御] の取得
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● オプション [薬の知識] の取得
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 武器オプション [ターン内先制] の取得
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 武器オプション [連続攻撃] の取得
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 防具オプション [クリティカル防止] の取得
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 防具オプション [消費 MP 半分] の取得
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 防具オプション [取得経験値 2 倍] の取得
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 防具オプション [HP 自動回復] の取得
  //--------------------------------------------------------------------------
  get auto_hp_recover() {
    let armor;
    for (armor of rb.compact(this.armors())) {
      if (armor.auto_hp_recover) {
        return true;
      }
    }
    return false;
  }
  //--------------------------------------------------------------------------
  // ● 通常攻撃 アニメーション ID の取得
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 通常攻撃 アニメーション ID の取得 (二刀流：武器２)
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 経験値の文字列取得
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 次のレベルの経験値の文字列取得
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 次のレベルまでの経験値の文字列取得
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 装備の変更 (ID で指定)
  //     equip_type : 装備部位 (0..4)
  //     item_id    : 武器 ID or 防具 ID
  //     test       : テストフラグ (戦闘テスト、または装備画面での一時装備)
  //    イベントコマンド、および戦闘テストの準備で使用する。
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 装備の変更 (オブジェクトで指定)
  //     equip_type : 装備部位 (0..4)
  //     item       : 武器 or 防具 (nil なら装備解除)
  //     test       : テストフラグ (戦闘テスト、または装備画面での一時装備)
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 装備の破棄
  //     item : 破棄する武器 or 防具
  //    武器／防具の増減で「装備品も含める」のとき使用する。
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 両手装備合法判定
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 装備可能判定
  //     item : アイテム
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 経験値の変更
  //     exp  : 新しい経験値
  //     show : レベルアップ表示フラグ
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● レベルアップ
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● レベルダウン
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● レベルアップメッセージの表示
  //     new_skills : 新しく習得したスキルの配列
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 経験値の獲得 (経験値 2 倍のオプションを考慮)
  //     exp  : 経験値の増加量
  //     show : レベルアップ表示フラグ
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● レベルの変更
  //     level : 新しいレベル
  //     show  : レベルアップ表示フラグ
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● スキルを覚える
  //     skill_id : スキル ID
  //--------------------------------------------------------------------------
  learn_skill(skill_id) {
    if (!(this.skill_learn_p(rb.idx($data_skills, skill_id)))) {
      rb.push(this._skills, skill_id);
      return rb.sort_bang(this._skills);
    }
  }
  //--------------------------------------------------------------------------
  // ● スキルを忘れる
  //     skill_id : スキル ID
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● スキルの習得済み判定
  //     skill : スキル
  //--------------------------------------------------------------------------
  skill_learn_p(skill) {
    return rb.include_p(this._skills, rb.id(skill));
  }
  //--------------------------------------------------------------------------
  // ● スキルの使用可能判定
  //     skill : スキル
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 名前の変更
  //     name : 新しい名前
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● 職業 ID の変更
  //     class_id : 新しい職業 ID
  //--------------------------------------------------------------------------
  //--------------------------------------------------------------------------
  // ● グラフィックの変更
  //     character_name  : 新しい歩行グラフィック ファイル名
  //     character_index : 新しい歩行グラフィック インデックス
  //     face_name       : 新しい顔グラフィック ファイル名
  //     face_index      : 新しい顔グラフィック インデックス
  //--------------------------------------------------------------------------
  set_graphic(character_name, character_index, face_name, face_index) {
    this._character_name = character_name;
    this._character_index = character_index;
    this._face_name = face_name;
    return this._face_index = face_index;
  }
  // fora do escopo (nada do jogo chama): actor?, index, skills, element_rate, state_probability, state_resist?, element_set, plus_state_set, hit, eva, cri, odds, fix_equipment, auto_battle, super_guard, pharmacology, fast_attack, dual_attack, prevent_critical, half_mp_cost, double_exp_gain, atk_animation_id, atk_animation_id2, exp_s, next_exp_s, next_rest_exp_s, change_equip_by_id, change_equip, discard_equip, two_hands_legal?, equippable?, change_exp, level_up, level_down, display_level_up, gain_exp, change_level, forget_skill, skill_can_use?, name=, class_id=, use_sprite?, perform_collapse, do_auto_recovery, make_action
});
